import numpy as np
import pandas as pd


def generate_synthetic_burnin_dataset(num_samples: int = 150, random_seed: int = 42) -> pd.DataFrame:
    """
    Generates synthetic semiconductor burn-in screening data mimicking high-temperature operating life (HTOL)
    in compliance with JEDEC JESD22-A108 and MIL-STD-883 standards.
    
    NOTE: All data generated by this module is purely SYNTHETIC for demonstration,
    validation, and academic evaluation purposes.
    """
    np.random.seed(random_seed)

    lots = ["LOT-2026-A1", "LOT-2026-B2", "LOT-2026-C3", "LOT-2026-D4"]
    comp_types = ["Power MOSFET (SiC)", "GaN HEMT", "IGBT Driver IC", "Precision Voltage Ref"]

    rows = []
    for i in range(1, num_samples + 1):
        comp_id = f"CMP-{1000 + i}"
        lot = np.random.choice(lots, p=[0.35, 0.35, 0.20, 0.10])
        comp_type = np.random.choice(comp_types, p=[0.4, 0.3, 0.2, 0.1])
        temp_c = float(np.random.normal(125.0, 2.5)) # Burn-in chamber stress temperature (125°C)

        # Baseline nominal voltage (e.g. threshold voltage Vth ~ 3.3V or reference 5.0V)
        base_v = float(np.random.normal(3.30, 0.05))
        leakage_ua = float(np.random.exponential(1.2) + 0.1)

        # Class determination:
        # ~85% PASS (healthy, stable minimal drift)
        # ~10% FLAG (latent defects, oxide degradation, elevated drift slope or high leakage)
        # ~3% INFANT MORTALITY (severe breakdown, steep slope)
        # ~2% INVALID DATA (sensor glitch, missing read, negative physical values)
        rand_val = np.random.rand()

        if rand_val < 0.84:
            # Healthy component: natural subtle physical drift (thermal settling)
            v_0h = round(base_v, 4)
            # Drift rate around 0.0001 - 0.0005 V / hour
            drift_rate = np.random.normal(0.00025, 0.0001)
            v_24h = round(v_0h + drift_rate * 24 + np.random.normal(0, 0.002), 4)
            v_48h = round(v_0h + drift_rate * 48 + np.random.normal(0, 0.003), 4)
            v_72h = round(v_0h + drift_rate * 72 + np.random.normal(0, 0.004), 4)
            v_168h_actual = round(v_0h + drift_rate * 168 + np.random.normal(0, 0.005), 4)
            ground_truth_status = "PASS"

        elif rand_val < 0.94:
            # Latent Degradation: Gate oxide breakdown or trap charges causing excessive parameter shift
            v_0h = round(base_v, 4)
            elevated_drift = np.random.uniform(0.0018, 0.0035) * np.random.choice([1, -1])
            v_24h = round(v_0h + elevated_drift * 24 + np.random.normal(0, 0.005), 4)
            v_48h = round(v_0h + elevated_drift * 48 + np.random.normal(0, 0.008), 4)
            v_72h = round(v_0h + elevated_drift * 72 + np.random.normal(0, 0.012), 4)
            v_168h_actual = round(v_0h + elevated_drift * 168 + np.random.normal(0, 0.015), 4)
            leakage_ua = float(np.random.uniform(8.5, 45.0)) # Elevated leakage
            ground_truth_status = "FLAG"

        elif rand_val < 0.98:
            # Severe defect / Infant Mortality
            v_0h = round(base_v, 4)
            severe_drift = np.random.uniform(0.0045, 0.0090) * np.random.choice([1, -1])
            v_24h = round(v_0h + severe_drift * 24, 4)
            v_48h = round(v_0h + severe_drift * 48, 4)
            v_72h = round(v_0h + severe_drift * 72, 4)
            v_168h_actual = round(v_0h + severe_drift * 168, 4)
            leakage_ua = float(np.random.uniform(50.0, 180.0))
            ground_truth_status = "FLAG"

        else:
            # Deliberate Data Quality Anomaly / Invalid Telemetry
            v_0h = round(base_v, 4)
            v_24h = np.nan if np.random.rand() > 0.5 else -0.5 # Missing or unphysical negative reading
            v_48h = round(base_v + 0.02, 4)
            v_72h = round(base_v + 0.04, 4)
            v_168h_actual = np.nan
            leakage_ua = -1.0 # Invalid physical current
            ground_truth_status = "INVALID DATA"

        rows.append({
            "component_id": comp_id,
            "lot_number": lot,
            "component_type": comp_type,
            "v_0h": v_0h,
            "v_24h": v_24h,
            "v_48h": v_48h,
            "v_72h": v_72h,
            "v_168h_actual": v_168h_actual,
            "temp_c": round(temp_c, 1),
            "leakage_current_ua": round(leakage_ua, 2),
            "true_status": ground_truth_status,
            "is_synthetic": True
        })

    return pd.DataFrame(rows)


def get_sample_csv_bytes() -> bytes:
    df = generate_synthetic_burnin_dataset(120, random_seed=101)
    return df.to_csv(index=False).encode("utf-8")
